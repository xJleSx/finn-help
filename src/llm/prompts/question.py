def build_question_message(
    question: str,
    profile: str,
    market_context: str = "",
    ticker_context: str = "",
) -> str:
    ctx_block = ""
    if market_context.strip():
        ctx_block = f"Текущая рыночная ситуация:\n{market_context}\n"

    tkr_block = ""
    if ticker_context.strip():
        tkr_block = f"Данные об инструменте из БД:\n{ticker_context}\n"

    return QUESTION_USER_TEMPLATE.format(
        question=question,
        market_context=ctx_block,
        ticker_context=tkr_block,
        profile=profile,
    )
